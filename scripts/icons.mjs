import { readFile, writeFile, mkdir, copyFile, readdir, unlink } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(await readFile(path.join(root, 'scripts/icons.json'), 'utf8'));
const packages = { lucide: 'lucide-static', lobe: '@lobehub/icons-static-svg' };
const expected = {lucide: '1.60.0', lobe: '1.98.0'};
const used = new Set();
const output = path.join(root, 'internal/icons');
const svgDir = path.join(output, 'svg');
await mkdir(svgDir, {recursive: true});
let code = '// Code generated by scripts/icons.mjs; DO NOT EDIT.\npackage icons\n\nimport (\n "embed"\n "github.com/egoist/mygo/ui"\n)\n\n//go:embed svg/*.svg\nvar resources embed.FS\n\nfunc load(name string)*ui.SVG{data,err:=resources.ReadFile("svg/"+name+".svg");if err!=nil{panic(err)};return ui.MustParseSVG(data)}\n\nvar (\n';
const exported = [];
const written = new Set();
const take = (name) => {
  if (!/^[A-Z][a-zA-Z0-9]*$/.test(name) || used.has(name)) throw new Error(`Invalid or duplicate icon ${name}`);
  used.add(name);
};
const check = (svg, file) => {
  if (!svg.includes('<svg') || !svg.includes('viewBox=') || svg.includes('<script')) throw new Error(`Invalid SVG ${file}`);
};
for (const [source, icons] of Object.entries(manifest)) {
  if (source === 'color') {
    for (const [name, file] of Object.entries(icons)) {
      take(name);
      const svg = await readFile(path.join(root, 'assets/agent-logos', file+'.svg'), 'utf8');
      check(svg, file);
      const target = `color-${file}`;
      await writeFile(path.join(svgDir, target+'.svg'), svg);
      written.add(target+'.svg');
      code += ` ${name} = load("${target}")\n`;
      exported.push(`color assets/agent-logos/${file}.svg -> ${target}.svg (ui.Image, brand color)`);
    }
    continue;
  }
  const pkg = path.join(root, 'node_modules', packages[source]);
  const metadata = JSON.parse(await readFile(path.join(pkg, 'package.json'), 'utf8'));
  if(metadata.version !== expected[source]) throw new Error(`Unexpected ${source} version ${metadata.version}`);
  for (const [name, file] of Object.entries(icons)) {
    take(name);
    const svg = await readFile(path.join(pkg, 'icons', file+'.svg'), 'utf8');
    check(svg, file);
    const target = `${source}-${file}`;
    await writeFile(path.join(svgDir, target+'.svg'), svg);
    written.add(target+'.svg');
    code += ` ${name} = load("${target}")\n`;
    exported.push(`${source} ${metadata.version} icons/${file}.svg -> ${target}.svg (ui.Icon, monochrome)`);
  }
}
for (const file of await readdir(svgDir)) {
  if (file.endsWith('.svg') && !written.has(file)) await unlink(path.join(svgDir, file));
}
code += ')\n';
await writeFile(path.join(output, 'icons_gen.go'), code);
execFileSync('gofmt', ['-w', path.join(output, 'icons_gen.go')]);
await writeFile(path.join(output, 'SOURCES.txt'), exported.join('\n')+'\n');
await copyFile(path.join(root, 'node_modules/lucide-static/LICENSE'), path.join(output, 'LICENSE-lucide'));
await copyFile(path.join(root, 'assets/licenses/lobe-icons-1.98.0.LICENSE'), path.join(output, 'LICENSE-lobe'));
